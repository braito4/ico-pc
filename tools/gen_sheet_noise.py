#!/usr/bin/env python3
"""Generate port/shaders/sheet_noise.hlsli: the menu text's grain threshold.

font_sheet_ps (port/shaders/font.hlsl, sheet_text.hlsli sheet_threshold)
quantises the menu text's opacity against a threshold that changes from texel
to texel, the irregular grain of the game's 4-bit menu sheets. The threshold
is a 32 x 32 blue-noise tile: Ulichney's void-and-cluster method on a torus
with a Gaussian filter of sigma 1.5 texels, from a fixed seed, so the table
is the same on every run. The 1024 ranks are divided by 4, so each value 0..255
appears four times.

The output holds preprocessor lines only (SHEET_NOISE_WORDS: 256 words, the
row y's texel x in byte x & 3 of word y * 8 + x / 4), so the uniform buffer
the shader reads (port/render/rd_tex.c rd__sheet_noise_binding) and the CPU
reference (port/render/test/sheet_ref.c) hold the same bytes.

The energies are integers (the filter's taps in 2^-20, rounded), so the
order of the placements, and the table, do not depend on the platform's
floating point.

Usage:
    tools/gen_sheet_noise.py            # write port/shaders/sheet_noise.hlsli
    tools/gen_sheet_noise.py --check    # exit 1 if it is out of date
"""

import argparse
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "port", "shaders", "sheet_noise.hlsli")

N = 32  # the tile's side
SIGMA = 1.5
SEED = 0x1C0
INITIAL = N * N // 10  # the initial pattern's ones


def kernel():
    """The toroidal Gaussian's taps by offset (dx, dy) mod N, in 2^-20."""
    k = [[0] * N for _ in range(N)]
    for dy in range(N):
        for dx in range(N):
            ex = min(dx, N - dx)
            ey = min(dy, N - dy)
            k[dy][dx] = int(round(math.exp(-(ex * ex + ey * ey) / (2.0 * SIGMA * SIGMA)) * (1 << 20)))
    return k


class Field:
    """A binary pattern and every texel's energy (the filter over its ones)."""

    def __init__(self, k):
        self.k = k
        self.bits = [0] * (N * N)
        self.energy = [0] * (N * N)

    def set(self, i, v):
        if self.bits[i] == v:
            return
        self.bits[i] = v
        sign = 1 if v else -1
        x0, y0 = i % N, i // N
        e = self.energy
        for y in range(N):
            row = self.k[(y - y0) % N]
            base = y * N
            for x in range(N):
                e[base + x] += sign * row[(x - x0) % N]

    def tightest(self, bit):
        """The texel holding bit with the highest energy of the ones (bit 1)
        or the lowest (bit 0: the emptiest void); the first on a tie."""
        best, bi = None, -1
        for i in range(N * N):
            if self.bits[i] != bit:
                continue
            e = self.energy[i]
            if best is None or (e > best if bit else e < best):
                best, bi = e, i
        return bi


def lcg(state):
    state = (state * 6364136223846793005 + 1442695040888963407) & 0xFFFFFFFFFFFFFFFF
    return state, state >> 33


def generate():
    k = kernel()
    f = Field(k)
    # the initial pattern: INITIAL ones at random texels
    state = SEED
    placed = 0
    while placed < INITIAL:
        state, r = lcg(state)
        i = r % (N * N)
        if not f.bits[i]:
            f.set(i, 1)
            placed += 1
    # spread it: the tightest cluster's one moves to the largest void until
    # it would move back
    while True:
        c = f.tightest(1)
        f.set(c, 0)
        v = f.tightest(0)
        if v == c:
            f.set(c, 1)
            break
        f.set(v, 1)
    initial = list(f.bits)
    rank = [0] * (N * N)
    # phase 1: the ones of the initial pattern ranked down, tightest first
    g = Field(k)
    for i in range(N * N):
        if initial[i]:
            g.set(i, 1)
    for r in range(INITIAL - 1, -1, -1):
        c = g.tightest(1)
        g.set(c, 0)
        rank[c] = r
    # phase 2: up to half full, each into the largest void
    g = Field(k)
    for i in range(N * N):
        if initial[i]:
            g.set(i, 1)
    r = INITIAL
    while r < N * N // 2:
        v = g.tightest(0)
        g.set(v, 1)
        rank[v] = r
        r += 1
    # phase 3: the rest, each at the tightest cluster of the zeros (the
    # minority now): the energy of the zeros' pattern
    z = Field(k)
    for i in range(N * N):
        if not g.bits[i]:
            z.set(i, 1)
    while r < N * N:
        c = z.tightest(1)
        z.set(c, 0)
        rank[c] = r
        r += 1
    return [v >> 2 for v in rank]


def render(vals):
    words = []
    for y in range(N):
        for x in range(0, N, 4):
            w = 0
            for b in range(4):
                w |= vals[y * N + x + b] << (8 * b)
            words.append(w)
    lines = [
        "// sheet_noise.hlsli: the menu text's grain, a 32 x 32 blue-noise tile.",
        "// Generated by tools/gen_sheet_noise.py (void-and-cluster, toroidal",
        "// Gaussian sigma %.1f, seed 0x%X); do not edit, run the script." % (SIGMA, SEED),
        "// Each value 0..255 appears 4 times.  Texel (x, y) is byte x & 3 of word",
        "// y * 8 + x / 4.  Preprocessor lines only: port/render/rd_tex.c (the",
        "// uniform buffer font_sheet_ps reads, sheet_text.hlsli) and",
        "// port/render/test/sheet_ref.c hold the same words.",
        "#ifndef ICO_SHEET_NOISE_HLSLI",
        "#define ICO_SHEET_NOISE_HLSLI",
        "",
        "#define SHEET_NOISE_SIZE %d" % N,
        "#define SHEET_NOISE_WORDS \\",
    ]
    for row in range(N):
        chunk = words[row * 8 : row * 8 + 8]
        text = ", ".join("0x%08Xu" % w for w in chunk)
        tail = ", \\" if row < N - 1 else ""
        lines.append("    " + text + tail)
    lines += ["", "#endif // ICO_SHEET_NOISE_HLSLI", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(generate())
    if args.check:
        try:
            with open(OUT, encoding="utf-8") as fp:
                cur = fp.read()
        except OSError:
            cur = None
        if cur != text:
            print("%s is out of date: run tools/gen_sheet_noise.py" % os.path.relpath(OUT, ROOT))
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fp:
        fp.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
